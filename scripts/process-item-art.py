"""Prepare individually generated magenta-key item art for offline UI use.
Usage: python scripts/process-item-art.py .artifacts/item-art/raw
Only supplied PNGs are processed; existing other icons remain untouched.
Pillow is a development-only dependency; game builds use the checked-in WebPs.
"""
from pathlib import Path
import hashlib,json,sys
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
raw=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'.artifacts/item-art/raw'
out=ROOT/'web/assets/items';out.mkdir(parents=True,exist_ok=True)
masters=ROOT/'.artifacts/item-art/transparent';masters.mkdir(parents=True,exist_ok=True)
manifest_path=out/'manifest.json'
manifest=json.loads(manifest_path.read_text()) if manifest_path.exists() else {'schema':1,'style':'original colored survival inventory illustrations','source':'AI-generated individually for Oskol; chroma key removed; no third-party game assets','items':{}}
for path in sorted(raw.glob('*.png')):
    im=Image.open(path).convert('RGBA')
    # None of these objects contain magenta. Keying internal holes as well as
    # the outside avoids pink islands inside rings, handles and cloth gaps.
    pixels=[]
    for r,g,b,a in (getattr(im,'get_flattened_data',None) or im.getdata)():
        magenta=min(r,b)-g
        if r>110 and b>100 and magenta>45:
            a=0
        pixels.append((r,g,b,a))
    im.putdata(pixels)
    bounds=im.getbbox()
    if not bounds: raise ValueError(f'Empty artwork: {path}')
    im=im.crop(bounds)
    def fitted(size):
        part=im.copy();part.thumbnail((round(size*.88),round(size*.88)),Image.Resampling.LANCZOS)
        canvas=Image.new('RGBA',(size,size));canvas.alpha_composite(part,((size-part.width)//2,(size-part.height)//2));return canvas
    fitted(1024).save(masters/(path.stem+'.png'),optimize=True)
    target=out/(path.stem+'.webp')
    fitted(256).save(target,format='WEBP',lossless=True,method=6,exact=True)
    data=target.read_bytes()
    manifest['items'][path.stem]={'file':target.name,'width':256,'height':256,'alpha':True,'sha256':hashlib.sha256(data).hexdigest(),'sourceSha256':hashlib.sha256(path.read_bytes()).hexdigest()}
manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
registry='// Generated by scripts/process-item-art.py. Individually illustrated color icons.\nexport const ITEM_ART=Object.freeze('+json.dumps({k:'assets/items/'+v['file']+'?v='+v['sha256'][:10] for k,v in manifest['items'].items()},indent=2)+');\n'
(ROOT/'src/survival/item-art.js').write_text(registry)
print(f'Prepared {len(manifest["items"])} transparent 256px WebP assets')
